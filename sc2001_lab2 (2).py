def generate_connected_graph(n, m, max_weight=20):
    """
    Generates a random connected undirected graph with n vertices and m edges.
    Returns both (adj_matrix, adj_list) representing the exact same graph.

    Parameters:
        n (int): Number of vertices (|V|)
        m (int): Number of edges (|E|)
        max_weight (int): Maximum edge weight (weights drawn from 1 to max_weight)
    """
    max_possible_edges = n * (n - 1) // 2
    if m < n - 1:
        raise ValueError(f"For a connected graph, m must be >= n - 1 ({n - 1}), but got {m}.")
    if m > max_possible_edges:
        raise ValueError(f"Too many edges: maximum possible for n={n} is {max_possible_edges}, but got {m}.")

    INF = math.inf

    # Initialize empty structures
    matrix = [[INF] * n for _ in range(n)]
    for i in range(n):
        matrix[i][i] = 0

    adj_list = [[] for _ in range(n)]

    # Step 1: Ensure connectivity via a random spanning tree (n - 1 edges)
    vertices = list(range(n))
    random.shuffle(vertices)

    edges = set()
    for i in range(1, n):
        u = vertices[i]
        v = vertices[random.randint(0, i - 1)]
        edge_key = (min(u, v), max(u, v))
        edges.add(edge_key)

    # Step 2: Sample the remaining m - (n - 1) edges
    while len(edges) < m:
        u = random.randrange(n)
        v = random.randrange(n)
        if u == v:
            continue
        edge_key = (min(u, v), max(u, v))
        edges.add(edge_key)

    # Step 3: Populate both structures with identical weights
    for u, v in edges:
        w = random.randint(1, max_weight)

        # Populate matrix (undirected)
        matrix[u][v] = w
        matrix[v][u] = w

        # Populate adjacency list (undirected)
        adj_list[u].append((v, w))
        adj_list[v].append((u, w))

    return matrix, adj_list

"""## 2. Part (a): Adjacency Matrix + Array Priority Queue

### 2.1 Data Structures

The graph \(G=(V,E)\) is stored in an adjacency matrix:

adj[u][v] =
\begin{cases}
w(u,v), & \text{if } (u,v)\in E \\
\infty, & \text{otherwise}
\end{cases}


The priority queue is implemented using an ordinary array. In each iteration, we scan all vertices to find the unvisited vertex with the smallest tentative distance.
"""

def dijkstra_matrix(adj, src):

  n = len(adj) # Number of vertices |V|
  INF = math.inf

  # Initialize distances to infinity and visited flags to False
  dist = [INF] * n
  visited = [False] * n
  dist[src] = 0  # Distance from source to itself is 0

  # Main loop: iterate |V| times (or until all reachable vertices are processed)
  for _ in range(n):
    # Array priority queue: find the unvisited vertex with minimum distance
    u = -1
    best = INF
    for i in range(n):

      if not visited[i] and dist[i] < best:
        best = dist[i]
        u = i

    # If no reachable unvisited vertex remains, break early
    if u == -1:
      break

    # Mark the selected vertex as visited
    visited[u] = True

    # --- Relax all outgoing edges from u ---
    # Since we use an adjacency matrix, we scan the entire row adj[u][*]
    for v in range(n):
      if not visited[v] and adj[u][v] != INF:
        new_dist = dist[u] + adj[u][v]
        if new_dist < dist[v]:
          dist[v] = new_dist

  return dist


